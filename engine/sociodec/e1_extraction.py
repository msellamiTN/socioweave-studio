"""Frozen E1 three-extractor union and human-audit protocol.

The paper specifies q=3 extractors, union aggregation and a 20% human audit.
It does not specify the audit sampling algorithm or rounding rule. This module
therefore makes those operational choices explicit and content-addressed:
SHA-256 rank sampling without replacement, with ceil(0.2 * population_size).
No audit decision is generated by software; all sampled items remain pending
until a named human reviewer supplies a timestamped decision and rationale.
"""
from __future__ import annotations

import hashlib
import math
import re
import unicodedata
from datetime import datetime
from dataclasses import asdict, is_dataclass
from enum import Enum
from typing import Mapping, Sequence

from sociodec.datasets import E1FrozenSnapshot
from sociodec.extraction import AggregatedExtraction, ExtractionResult, aggregate_extractions
from sociodec.experiments import content_hash

E1_EXTRACTION_SCHEMA = "e1-extraction-audit-bundle-v1"
AUDIT_DECISIONS = {"correct", "incorrect", "incomplete", "ambiguous"}


def _jsonable(value: object) -> object:
    if isinstance(value, Enum):
        return value.value
    if is_dataclass(value):
        return _jsonable(asdict(value))
    if isinstance(value, Mapping):
        return {str(key): _jsonable(item) for key, item in value.items()}
    if isinstance(value, (tuple, list)):
        return [_jsonable(item) for item in value]
    if value is None or isinstance(value, (str, int, float, bool)):
        return value
    raise TypeError(f"Unsupported extraction manifest value: {type(value).__name__}")


def _normalise(value: str) -> str:
    text = unicodedata.normalize("NFKC", value).casefold()
    return re.sub(r"\s+", " ", re.sub(r"[^\w\s]", " ", text)).strip()


def _requirement_key(item: object) -> str:
    kind = getattr(getattr(item, "type", None), "value", "")
    domain = getattr(item, "domain", "")
    statement = _normalise(getattr(item, "statement", ""))
    return f"{kind}|{domain}|{statement}"


def _extractor_output(result: ExtractionResult) -> dict[str, object]:
    payload = {
        "extractor_id": result.extractor_id,
        "requirements": _jsonable(result.requirements),
        "hypotheses": _jsonable(result.hypotheses),
        "entities": _jsonable(result.entities),
        "ambiguities": _jsonable(result.ambiguities),
        "conflicts": _jsonable(result.conflicts),
    }
    payload["typed_output_sha256"] = content_hash(payload)
    payload["raw_response_sha256"] = (
        hashlib.sha256(result.raw_response.encode("utf-8")).hexdigest()
        if result.raw_response is not None else None
    )
    return payload


def _union_items(dataset: str, example_id: str, aggregate: AggregatedExtraction) -> list[dict[str, object]]:
    items: list[dict[str, object]] = []
    for kind, values, sources in (
        ("explicit_requirement", aggregate.requirements, aggregate.requirement_sources),
        ("implicit_hypothesis", aggregate.hypotheses, aggregate.hypothesis_sources),
    ):
        for item in values:
            key = _requirement_key(item)
            item_id = content_hash({
                "dataset": dataset, "example_id": example_id,
                "kind": kind, "provenance_key": key,
            })
            items.append({
                "item_id": item_id, "dataset": dataset, "example_id": example_id,
                "kind": kind, "statement": item.statement, "type": item.type.value,
                "domain": item.domain, "extractor_sources": list(sources.get(key, ())),
                "item_sha256": content_hash(_jsonable(item)),
            })
    return items


def _bundle_hash(bundle: Mapping[str, object]) -> str:
    return content_hash({key: value for key, value in bundle.items() if key != "bundle_sha256"})


def build_e1_extraction_bundle(
    *,
    snapshot: E1FrozenSnapshot,
    extractor_roster: Sequence[Mapping[str, str]],
    results_by_prompt: Mapping[tuple[str, str], Sequence[ExtractionResult]],
    audit_seed: int,
) -> dict[str, object]:
    """Freeze q=3 outputs, conservative union and deterministic 20% audit tasks.

    extractor_roster entries require extractor_id, provider_org, model_id,
    model_revision and config_sha256. Distinct provider organizations are
    recorded, not required: the paper does not prescribe provider independence
    for the three extractors.
    """
    if isinstance(audit_seed, bool) or not isinstance(audit_seed, int) or audit_seed < 0:
        raise ValueError("audit_seed must be a non-negative integer")
    if len(extractor_roster) != 3:
        raise ValueError("E1 requires exactly three declared extractors (q=3)")
    required_roster_fields = {
        "extractor_id", "provider_org", "model_id", "model_revision", "config_sha256",
    }
    roster = []
    for entry in extractor_roster:
        if set(entry) != required_roster_fields or any(
            not isinstance(entry[field], str) or not entry[field].strip()
            for field in required_roster_fields
        ):
            raise ValueError("each extractor roster entry must declare exactly the required non-empty provenance fields")
        digest = entry["config_sha256"]
        if len(digest) != 64 or any(char not in "0123456789abcdef" for char in digest):
            raise ValueError("extractor config_sha256 must be a lowercase SHA-256 digest")
        roster.append(dict(entry))
    extractor_ids = [entry["extractor_id"] for entry in roster]
    if len(set(extractor_ids)) != 3:
        raise ValueError("the three extractor IDs must be distinct")
    expected_keys = {(item.dataset, item.example_id) for item in snapshot.examples}
    if set(results_by_prompt) != expected_keys:
        missing = sorted(expected_keys - set(results_by_prompt))
        extra = sorted(set(results_by_prompt) - expected_keys)
        raise ValueError(f"extractor outputs must cover the exact frozen prompt set; missing={missing[:3]}, extra={extra[:3]}")

    records = []
    union_items = []
    for example in snapshot.examples:
        key = (example.dataset, example.example_id)
        results = tuple(results_by_prompt[key])
        if len(results) != 3 or {item.extractor_id for item in results} != set(extractor_ids):
            raise ValueError(f"{key} must have exactly one output from each of the three declared extractors")
        by_id = {item.extractor_id: item for item in results}
        ordered_results = tuple(by_id[item] for item in extractor_ids)
        aggregate = aggregate_extractions(ordered_results)
        output_records = [_extractor_output(item) for item in ordered_results]
        prompt_items = _union_items(example.dataset, example.example_id, aggregate)
        union_items.extend(prompt_items)
        records.append({
            "dataset": example.dataset,
            "example_id": example.example_id,
            "prompt_sha256": example.prompt_hash,
            "extractor_outputs": output_records,
            "union_item_ids": [item["item_id"] for item in prompt_items],
            "union_sha256": content_hash(prompt_items),
        })

    if not union_items:
        raise ValueError("E1 extraction union is empty; no requirement or hypothesis items can be audited")
    if len({item["item_id"] for item in union_items}) != len(union_items):
        raise ValueError("E1 extraction union contains duplicate item identities")
    audit_count = math.ceil(0.20 * len(union_items))
    ranked = sorted(
        union_items,
        key=lambda item: (
            hashlib.sha256(f"{audit_seed}\0{item['item_id']}".encode("utf-8")).hexdigest(),
            item["item_id"],
        ),
    )
    audit_tasks = [
        {
            "item_id": item["item_id"], "dataset": item["dataset"],
            "example_id": item["example_id"], "kind": item["kind"],
            "statement": item["statement"], "item_sha256": item["item_sha256"],
            "extractor_sources": item["extractor_sources"], "status": "pending",
        }
        for item in ranked[:audit_count]
    ]
    bundle: dict[str, object] = {
        "schema_version": E1_EXTRACTION_SCHEMA,
        "paper_protocol": {
            "extractor_count": 3,
            "aggregation": "union",
            "human_audit_fraction": 0.20,
        },
        "operational_protocol": {
            "union_deduplication": "NFKC_casefold_punctuation_whitespace_exact_match_within_type_and_domain",
            "audit_sampling": "sha256_ranked_without_replacement_over_campaign_union_items",
            "audit_rounding": "ceil",
            "audit_seed": audit_seed,
            "sampling_note": "Deterministic sampling and ceil rounding are explicit implementation choices; the paper specifies 20% but not this algorithm or rounding rule.",
            "audit_population": "deduplicated explicit requirements and implicit hypotheses; entities, ambiguity flags and conflict pairs are retained in extractor outputs but are not audit sampling units",
        },
        "extractor_roster": roster,
        "snapshot_sha256": snapshot.manifest["snapshot_sha256"],
        "prompt_count": len(records),
        "union_item_count": len(union_items),
        "audit_item_count": audit_count,
        "records": records,
        "union_items": union_items,
        "audit_tasks": audit_tasks,
        "audit_status": "pending",
        "audit_decisions": [],
    }
    bundle["bundle_sha256"] = _bundle_hash(bundle)
    return bundle


def apply_human_audit(
    bundle: Mapping[str, object],
    decisions: Sequence[Mapping[str, str]],
) -> dict[str, object]:
    """Attach explicit human decisions; never creates reviewer decisions itself."""
    if bundle.get("schema_version") != E1_EXTRACTION_SCHEMA or bundle.get("bundle_sha256") != _bundle_hash(bundle):
        raise ValueError("E1 extraction bundle schema or content hash is invalid")
    tasks = bundle.get("audit_tasks")
    if not isinstance(tasks, list):
        raise ValueError("E1 audit task list is missing")
    expected_ids = {item["item_id"] for item in tasks}
    received_ids = [item.get("item_id") for item in decisions]
    if len(received_ids) != len(set(received_ids)) or set(received_ids) != expected_ids:
        raise ValueError("human audit decisions must cover every sampled item exactly once")
    normalized = []
    for decision in decisions:
        if set(decision) != {"item_id", "reviewer_id", "decision", "rationale", "reviewed_at"}:
            raise ValueError("each human audit decision must declare exactly item_id, reviewer_id, decision, rationale and reviewed_at")
        if not all(isinstance(decision[field], str) and decision[field].strip()
                   for field in decision):
            raise ValueError("human audit decision fields must be non-empty strings")
        if decision["decision"] not in AUDIT_DECISIONS:
            raise ValueError(f"unsupported human audit decision: {decision['decision']}")
        try:
            timestamp = datetime.fromisoformat(decision["reviewed_at"].replace("Z", "+00:00"))
        except ValueError as exc:
            raise ValueError("reviewed_at must be an ISO-8601 timestamp") from exc
        if timestamp.tzinfo is None or timestamp.utcoffset() is None:
            raise ValueError("reviewed_at must include a timezone offset")
        normalized.append(dict(decision))
    updated = dict(bundle)
    updated["audit_decisions"] = sorted(normalized, key=lambda item: item["item_id"])
    decision_by_id = {item["item_id"]: item for item in normalized}
    updated["audit_tasks"] = [
        {**task, "status": "audited", "decision": decision_by_id[task["item_id"]]["decision"],
         "reviewer_id": decision_by_id[task["item_id"]]["reviewer_id"],
         "rationale": decision_by_id[task["item_id"]]["rationale"],
         "reviewed_at": decision_by_id[task["item_id"]]["reviewed_at"]}
        for task in tasks
    ]
    updated["audit_status"] = "complete"
    updated["bundle_sha256"] = _bundle_hash(updated)
    return updated


def validate_e1_extraction_bundle(
    bundle: Mapping[str, object],
    *,
    snapshot: E1FrozenSnapshot,
    require_human_audit: bool = True,
) -> None:
    """Validate extraction completeness, q=3, union identity and audit coverage."""
    if bundle.get("schema_version") != E1_EXTRACTION_SCHEMA:
        raise ValueError("unknown E1 extraction bundle schema")
    if bundle.get("bundle_sha256") != _bundle_hash(bundle):
        raise ValueError("E1 extraction bundle SHA-256 does not match its contents")
    if bundle.get("snapshot_sha256") != snapshot.manifest.get("snapshot_sha256"):
        raise ValueError("E1 extraction bundle is bound to a different frozen dataset snapshot")
    protocol = bundle.get("paper_protocol")
    if protocol != {"extractor_count": 3, "aggregation": "union", "human_audit_fraction": 0.20}:
        raise ValueError("E1 extraction protocol must declare q=3, union and 20% human audit")
    roster = bundle.get("extractor_roster")
    required_roster_fields = {"extractor_id", "provider_org", "model_id", "model_revision", "config_sha256"}
    if not isinstance(roster, list) or len(roster) != 3 or len({item.get("extractor_id") for item in roster}) != 3:
        raise ValueError("E1 extraction bundle must contain three unique extractor identities")
    for entry in roster:
        if set(entry) != required_roster_fields or any(
            not isinstance(entry.get(field), str) or not entry[field].strip()
            for field in required_roster_fields
        ):
            raise ValueError("E1 extractor roster provenance is incomplete")
        digest = entry["config_sha256"]
        if len(digest) != 64 or any(char not in "0123456789abcdef" for char in digest):
            raise ValueError("E1 extractor configuration hash is invalid")
    expected = {(item.dataset, item.example_id): item for item in snapshot.examples}
    records = bundle.get("records")
    if not isinstance(records, list) or len(records) != len(expected):
        raise ValueError("E1 extraction bundle must contain one record per frozen prompt")
    seen = set()
    for record in records:
        key = (record.get("dataset"), record.get("example_id"))
        if key not in expected or key in seen:
            raise ValueError(f"unexpected or duplicate E1 extraction prompt record: {key}")
        seen.add(key)
        if record.get("prompt_sha256") != expected[key].prompt_hash:
            raise ValueError(f"E1 extraction prompt hash mismatch: {key}")
        outputs = record.get("extractor_outputs")
        if not isinstance(outputs, list) or len(outputs) != 3:
            raise ValueError(f"E1 extraction record must contain three extractor outputs: {key}")
        if {item.get("extractor_id") for item in outputs} != {item["extractor_id"] for item in roster}:
            raise ValueError(f"E1 extraction record has a missing or unexpected extractor: {key}")
        for output in outputs:
            typed_payload = {field: value for field, value in output.items()
                             if field not in {"typed_output_sha256", "raw_response_sha256"}}
            if output.get("typed_output_sha256") != content_hash(typed_payload):
                raise ValueError(f"E1 typed extractor output hash mismatch: {key}/{output.get('extractor_id')}")
            raw_hash = output.get("raw_response_sha256")
            if raw_hash is not None and (
                not isinstance(raw_hash, str) or len(raw_hash) != 64
                or any(char not in "0123456789abcdef" for char in raw_hash)
            ):
                raise ValueError(f"E1 raw extractor response hash is invalid: {key}/{output.get('extractor_id')}")
        if len(record.get("union_item_ids", [])) != len(set(record.get("union_item_ids", []))):
            raise ValueError(f"E1 extraction union contains duplicate item IDs: {key}")
    union = bundle.get("union_items")
    if not isinstance(union, list) or len(union) != bundle.get("union_item_count"):
        raise ValueError("E1 extraction union item count is inconsistent")
    union_ids = [item.get("item_id") for item in union]
    if len(union_ids) != len(set(union_ids)):
        raise ValueError("E1 extraction union item IDs are not unique")
    union_by_id = {item["item_id"]: item for item in union}
    record_by_key = {(item["dataset"], item["example_id"]): item for item in records}
    if set(record_by_key) != set(expected):
        raise ValueError("E1 extraction records do not cover the exact frozen prompt set")
    for key, record in record_by_key.items():
        prompt_union = [
            item for item in union
            if item.get("dataset") == key[0] and item.get("example_id") == key[1]
        ]
        prompt_ids = [item["item_id"] for item in prompt_union]
        if record.get("union_item_ids") != prompt_ids or record.get("union_sha256") != content_hash(prompt_union):
            raise ValueError(f"E1 per-prompt union fingerprint mismatch: {key}")
    task_count = math.ceil(0.20 * len(union))
    if bundle.get("audit_item_count") != task_count:
        raise ValueError("E1 human audit sample is not 20% of the frozen extraction union under the declared ceil rule")
    tasks = bundle.get("audit_tasks")
    if not isinstance(tasks, list) or len(tasks) != task_count:
        raise ValueError("E1 audit task list does not match the registered sample size")
    task_ids = [item.get("item_id") for item in tasks]
    if len(task_ids) != len(set(task_ids)) or not set(task_ids) <= set(union_ids):
        raise ValueError("E1 audit tasks contain duplicate or out-of-union item IDs")
    seed = bundle.get("operational_protocol", {}).get("audit_seed")
    if isinstance(seed, bool) or not isinstance(seed, int) or seed < 0:
        raise ValueError("E1 extraction bundle audit seed is invalid")
    expected_sample = [
        item["item_id"] for item in sorted(
            union,
            key=lambda item: (
                hashlib.sha256(f"{seed}\0{item['item_id']}".encode("utf-8")).hexdigest(),
                item["item_id"],
            ),
        )[:task_count]
    ]
    if task_ids != expected_sample:
        raise ValueError("E1 audit tasks differ from the deterministic frozen sample")
    for task in tasks:
        source = union_by_id[task["item_id"]]
        if any(task.get(field) != source.get(field) for field in (
            "item_id", "dataset", "example_id", "kind", "statement",
            "item_sha256", "extractor_sources",
        )):
            raise ValueError("E1 audit task differs from its frozen union item")
    if require_human_audit:
        if bundle.get("audit_status") != "complete" or any(item.get("status") != "audited" for item in tasks):
            raise ValueError("E1 human audit is incomplete; pending audit tasks cannot pass campaign validation")
        decisions = bundle.get("audit_decisions")
        if not isinstance(decisions, list) or {item.get("item_id") for item in decisions} != set(task_ids):
            raise ValueError("E1 human audit decisions do not cover the frozen sample")
        decision_by_id = {item["item_id"]: item for item in decisions}
        for task in tasks:
            decision = decision_by_id[task["item_id"]]
            if task.get("status") != "audited" or any(
                task.get(field) != decision.get(field)
                for field in ("decision", "reviewer_id", "rationale", "reviewed_at")
            ):
                raise ValueError("E1 audit task and recorded human decision differ")
            if decision.get("decision") not in AUDIT_DECISIONS or not all(
                isinstance(decision.get(field), str) and decision[field].strip()
                for field in ("reviewer_id", "rationale", "reviewed_at")
            ):
                raise ValueError("E1 human audit decision is incomplete or invalid")
            try:
                reviewed_at = datetime.fromisoformat(decision["reviewed_at"].replace("Z", "+00:00"))
            except ValueError as exc:
                raise ValueError("E1 human audit timestamp is not ISO-8601") from exc
            if reviewed_at.tzinfo is None or reviewed_at.utcoffset() is None:
                raise ValueError("E1 human audit timestamp must include a timezone offset")
